//! Durable DNS ownership by interface and process, serialized across nodes.

use std::{collections::BTreeMap, fs::{self, File, OpenOptions}, io::{self, Write}, path::{Path, PathBuf}, time::{Duration, Instant}};
use crate::apply::{self, ApplyError, Result};
use super::{Dns, resolved_unavailable};

pub(super) struct Managed {
    iface: String,
    root: PathBuf,
    resolv: PathBuf,
    prefer_resolved: bool,
}

#[derive(Default, serde::Serialize, serde::Deserialize)]
struct Journal {
    resolved: BTreeMap<String, Resolved>,
    file: Option<OriginalFile>,
    owners: Vec<Owner>,
    #[serde(default)] restore_pending: bool,
}
#[derive(serde::Serialize, serde::Deserialize)]
struct Resolved {
    dns: Vec<String>, domains: Vec<String>,
    #[serde(default)] process: Process,
}
#[derive(serde::Serialize, serde::Deserialize)]
struct OriginalFile {
    target: PathBuf, bytes: Option<Vec<u8>>,
    #[serde(default)] link: Option<PathBuf>,
    #[serde(default)] boot_id: String,
    #[serde(default)] last_written: Option<Vec<u8>>,
    #[serde(default)] previous_written: Option<Vec<u8>>,
    #[serde(default)] drift_delay: u64,
    #[serde(default)] drift_after_ms: u64,
}
#[derive(serde::Serialize, serde::Deserialize)]
struct Owner { iface: String, dns: Vec<String>, #[serde(default)] process: Process }
#[derive(Default, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
struct Process { pid: u32, start_time: String, boot_id: String }

#[cfg(target_os = "linux")]
fn process_start(pid: u32) -> io::Result<String> {
    let stat = fs::read_to_string(format!("/proc/{pid}/stat"))?;
    // comm may contain spaces and parentheses. Field 22 follows the final ')'.
    stat.rsplit_once(')').and_then(|(_, fields)| fields.split_whitespace().nth(19))
        .map(String::from).ok_or_else(|| io::Error::other("invalid process stat"))
}
impl Process {
    fn current() -> Result<Self> {
        #[cfg(target_os = "linux")]
        {
            let pid = std::process::id();
            let boot_id = fs::read_to_string("/proc/sys/kernel/random/boot_id")
                .map_err(|e| io_error("read", Path::new("/proc/sys/kernel/random/boot_id"), e))?;
            let start_time = process_start(pid).map_err(|e| io_error("read process start", Path::new("/proc"), e))?;
            Ok(Self { pid, start_time, boot_id: boot_id.trim().to_owned() })
        }
        // Managed is a Linux backend. Other platforms use native per-interface
        // DNS; this identity also lets its filesystem tests run on those hosts.
        #[cfg(all(unix, not(any(target_os = "linux", target_os = "macos"))))]
        { Ok(Self { pid: std::process::id(), start_time: String::new(), boot_id: "unix-pid-only".into() }) }
        #[cfg(any(target_os = "macos", not(unix)))]
        {
            static ID: std::sync::OnceLock<Process> = std::sync::OnceLock::new();
            Ok(ID.get_or_init(|| Self { pid: std::process::id(), start_time: format!("{:?}", std::time::SystemTime::now()), boot_id: "native-platform-tests".into() }).clone())
        }
    }
    fn alive(&self, current: &Self) -> bool {
        if self.boot_id != current.boot_id || self.pid == 0 { return false; }
        #[cfg(target_os = "linux")]
        { process_start(self.pid).is_ok_and(|start| start == self.start_time) }
        #[cfg(all(unix, not(any(target_os = "linux", target_os = "macos"))))]
        { process_exists(self.pid) }
        #[cfg(any(target_os = "macos", not(unix)))]
        { self == current }
    }
}
#[cfg(all(unix, any(test, not(any(target_os = "linux", target_os = "macos")))))]
fn process_exists(pid: u32) -> bool {
    let Ok(pid) = libc::pid_t::try_from(pid) else { return false; };
    if pid <= 0 { return false; }
    // SAFETY: signal zero only queries this positive PID; no signal is sent.
    unsafe { libc::kill(pid, 0) == 0 || io::Error::last_os_error().raw_os_error() == Some(libc::EPERM) }
}
fn now_ms() -> u64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| u64::try_from(d.as_millis()).unwrap_or(u64::MAX)).unwrap_or(0)
}
fn nm_generated(bytes: Option<&[u8]>) -> bool {
    bytes.is_some_and(|bytes| bytes.starts_with(b"# Generated by NetworkManager"))
}
fn stage_write(saved: &mut OriginalFile, bytes: &[u8]) {
    if saved.last_written.as_deref() != Some(bytes) {
        saved.previous_written = saved.last_written.take().or_else(|| saved.bytes.clone());
        saved.last_written = Some(bytes.to_vec());
    }
}
struct Locked { file: File, root: PathBuf, journal: Journal }

fn io_error(operation: &str, path: &Path, error: io::Error) -> ApplyError {
    ApplyError::io(&[operation, &path.to_string_lossy()], error)
}

impl Locked {
    fn open(root: &Path) -> Result<Self> {
        fs::create_dir_all(root).map_err(|e| io_error("mkdir", root, e))?;
        let path = root.join("lock");
        let file = OpenOptions::new().create(true).truncate(false).read(true).write(true).open(&path)
            .map_err(|e| io_error("open", &path, e))?;
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            match file.try_lock() {
                Ok(()) => break,
                Err(fs::TryLockError::WouldBlock) if Instant::now() < deadline => std::thread::sleep(Duration::from_millis(10)),
                Err(fs::TryLockError::WouldBlock) => return Err(io_error("lock", &path, io::Error::new(io::ErrorKind::TimedOut, "DNS state lock timeout"))),
                Err(fs::TryLockError::Error(e)) => return Err(io_error("lock", &path, e)),
            }
        }
        let mut state = Self { file, root: root.to_owned(), journal: Journal::default() };
        let path = root.join("state.json");
        match fs::read(&path) {
            Ok(bytes) => state.journal = serde_json::from_slice(&bytes).map_err(|e| ApplyError::new(&["parse", &path.to_string_lossy()], e.to_string()))?,
            Err(e) if e.kind() == io::ErrorKind::NotFound => {},
            Err(e) => return Err(io_error("read", &path, e)),
        }
        Ok(state)
    }
    fn save(&self) -> Result {
        let path = self.root.join("state.json");
        let bytes = serde_json::to_vec(&self.journal).map_err(|e| ApplyError::new(&["serialize", "DNS journal"], e.to_string()))?;
        let mut temp = tempfile::NamedTempFile::new_in(&self.root).map_err(|e| io_error("create", &path, e))?;
        temp.write_all(&bytes).and_then(|_| temp.as_file().sync_all()).map_err(|e| io_error("write", &path, e))?;
        temp.persist(&path).map_err(|e| io_error("rename", &path, e.error))?;
        #[cfg(unix)]
        File::open(&self.root).and_then(|dir| dir.sync_all()).map_err(|e| io_error("sync directory", &self.root, e))?;
        Ok(())
    }
}
impl Drop for Locked {
    fn drop(&mut self) {
        if let Err(error) = self.file.unlock() { tracing::warn!(%error, "failed to unlock DNS journal"); }
    }
}

fn target(path: &Path) -> Result<PathBuf> {
    // Resolve dangling symlinks too, while bounding cycles. Keep the actual link
    // text separately so a retarget to an alias of the same file is detectable.
    fn resolve(path: &Path, depth: usize) -> Result<PathBuf> {
        if depth > 40 { return Err(ApplyError::new(&["resolve", "resolver file"], "too many symbolic links")); }
        match fs::symlink_metadata(path) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                let link = fs::read_link(path).map_err(|e| io_error("readlink", path, e))?;
                let destination = if link.is_absolute() { link } else { path.parent().unwrap_or(Path::new("/")).join(link) };
                resolve(&destination, depth + 1)
            }
            Ok(_) => fs::canonicalize(path).map_err(|e| io_error("resolve", path, e)),
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                let parent = path.parent().ok_or_else(|| ApplyError::new(&["resolve", "resolver file"], "missing parent directory"))?;
                let name = path.file_name().ok_or_else(|| ApplyError::new(&["resolve", "resolver file"], "missing file name"))?;
                Ok(resolve(parent, depth + 1)?.join(name))
            }
            Err(e) => Err(io_error("stat", path, e)),
        }
    }
    resolve(path, 0)
}
fn link(path: &Path) -> Result<Option<PathBuf>> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => fs::read_link(path).map(Some).map_err(|e| io_error("readlink", path, e)),
        Ok(_) => Ok(None),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(io_error("stat", path, e)),
    }
}
fn read_bytes(path: &Path) -> Result<Option<Vec<u8>>> {
    match fs::read(path) {
        Ok(bytes) => Ok(Some(bytes)),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(io_error("read", path, e)),
    }
}
fn managed_target(path: &Path) -> bool {
    ["/run/NetworkManager", "/run/resolvconf", "/run/netconfig", "/run/connman", "/run/dhcpcd", "/var/lib/NetworkManager", "/var/run/NetworkManager", "/var/run/resolvconf", "/var/run/netconfig"]
        .iter().any(|dir| path.starts_with(dir))
}
fn read_original(path: &Path, process: &Process) -> Result<OriginalFile> {
    let target = target(path)?;
    if managed_target(&target) {
        return Err(ApplyError::new(&["DNS", "file fallback"], "resolver target is managed externally; enable systemd-resolved or configure DNS manually"));
    }
    let bytes = read_bytes(&target)?;
    if nm_generated(bytes.as_deref()) {
        return Err(ApplyError::new(&["DNS", "file fallback"], "NetworkManager-generated resolver file; enable systemd-resolved or configure DNS manually"));
    }
    Ok(OriginalFile { target, bytes, link: link(path)?, boot_id: process.boot_id.clone(), last_written: None,
        previous_written: None, drift_delay: 0, drift_after_ms: 0 })
}
fn file_body(dns: &[String]) -> Vec<u8> {
    format!("# fluxpeer exit-node\n{}", dns.iter().map(|s| format!("nameserver {s}\n")).collect::<String>()).into_bytes()
}
fn same_target(path: &Path, original: &OriginalFile) -> Result<bool> {
    Ok(link(path)? == original.link && target(path)? == original.target)
}
fn replace_file(original: &OriginalFile, bytes: Option<&[u8]>, runner: &mut impl apply::Runner) -> Result {
    if let Some(bytes) = bytes {
        runner.write_file(&original.target, bytes)
    } else {
        match fs::remove_file(&original.target) {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(io_error("remove", &original.target, e)),
        }
    }
}
fn resolved_values(output: &str) -> Result<Vec<String>> {
    let (_, values) = output.split_once(':').ok_or_else(|| ApplyError::new(&["parse", "resolvectl"], "missing link settings header"))?;
    Ok(values.split_whitespace().map(String::from).collect())
}
fn resolved_set(runner: &mut impl apply::Runner, command: &str, iface: &str, values: &[String]) -> Result {
    let mut args = vec!["resolvectl", command, iface];
    if values.is_empty() { args.push(""); } else { args.extend(values.iter().map(String::as_str)); }
    runner.run(&args, None).map(|_| ())
}

impl Managed {
    pub(super) fn new(iface: Option<&str>, prefer_resolved: bool) -> Self {
        Self { iface: iface.unwrap_or("fluxpeer").to_owned(), root: "/var/lib/fluxpeer/dns".into(), resolv: "/etc/resolv.conf".into(), prefer_resolved }
    }
    fn release_file(state: &mut Locked) -> Result {
        state.journal.owners.clear(); state.journal.file = None; state.journal.restore_pending = false; state.save()
    }
    // Cleanup relinquishes externally changed content. Active enforcement below
    // instead repairs drift; it never adopts the overwritten content as baseline.
    fn restore_file(&self, state: &mut Locked, runner: &mut impl apply::Runner) -> Result {
        let Some(original) = state.journal.file.as_ref() else { return Ok(()); };
        let actual = read_bytes(&original.target)?;
        if !same_target(&self.resolv, original)? || (actual != original.last_written && actual != original.previous_written) {
            tracing::warn!(path = %self.resolv.display(), "DNS externally taken over; releasing ownership without writes; check resolver manager and symlink configuration before enabling exit DNS again");
            return Self::release_file(state);
        }
        let body = state.journal.owners.last().map(|owner| file_body(&owner.dns));
        replace_file(original, body.as_deref().or(original.bytes.as_deref()), runner)?;
        if let Some(original) = state.journal.file.as_mut() { original.last_written = body; }
        if state.journal.owners.is_empty() { state.journal.file = None; }
        state.journal.restore_pending = false;
        state.save()
    }
    fn prune(&self, state: &mut Locked, current: &Process, runner: &mut impl apply::Runner) -> Result {
        // /run belongs to the previous boot. Never restore its persistent snapshot
        // into a newly created manager file; /etc originals survive for recovery.
        if state.journal.file.as_ref().is_some_and(|saved| saved.boot_id != current.boot_id && (saved.target.starts_with("/run") || saved.target.starts_with("/var/run"))) {
            Self::release_file(state)?;
        }
        let previous_top = state.journal.owners.last().map(|o| o.iface.clone());
        let count = state.journal.owners.len();
        state.journal.owners.retain(|owner| owner.process.alive(current));
        if state.journal.owners.len() != count {
            tracing::warn!("pruned expired DNS owners");
            // Persist a retry obligation if the top owner expired, including a
            // failed restoration that left live owners beneath it.
            state.journal.restore_pending |= previous_top != state.journal.owners.last().map(|o| o.iface.clone());
            state.save()?;
        }
        if state.journal.restore_pending || (state.journal.owners.is_empty() && state.journal.file.is_some()) {
            self.restore_file(state, runner)?;
        }
        let stale: Vec<String> = state.journal.resolved.iter().filter(|(_, saved)| !saved.process.alive(current)).map(|(iface, _)| iface.clone()).collect();
        for iface in stale {
            if let Some(saved) = state.journal.resolved.get(&iface) && saved.process.boot_id == current.boot_id {
                // Closing a dead process's TUN normally removes its resolved
                // link too. ENODEV means the per-link effect is already gone;
                // unavailable resolved state is discarded for expired owners.
                // Permission and other unexpected errors still fail.
                let gone = |result: Result| match result {
                    Err(error) if resolved_unavailable(&error) || (error.exit_code.is_some() && error.stderr.contains("No such device")) => {
                        tracing::warn!(%error, "expired DNS owner has no available resolved state; discarding stale entry");
                        Ok(())
                    },
                    result => result,
                };
                apply::all([gone(resolved_set(runner, "dns", &iface, &saved.dns)), gone(resolved_set(runner, "domain", &iface, &saved.domains))])?;
            }
            state.journal.resolved.remove(&iface); state.save()?;
        }
        Ok(())
    }
    #[cfg_attr(not(target_os = "linux"), allow(dead_code))]
    pub(super) fn owned(&self) -> Result<bool> {
        let path = self.root.join("state.json");
        let Some(bytes) = read_bytes(&path)? else { return Ok(false); };
        let state: Journal = serde_json::from_slice(&bytes).map_err(|e| ApplyError::new(&["parse", "DNS journal"], e.to_string()))?;
        Ok(state.resolved.contains_key(&self.iface) || state.owners.iter().any(|o| o.iface == self.iface))
    }
    fn set_file(&self, state: &mut Locked, dns: Vec<String>, process: &Process, runner: &mut impl apply::Runner) -> Result {
        self.set_file_at(state, dns, process, runner, now_ms())
    }
    fn set_file_at(&self, state: &mut Locked, dns: Vec<String>, process: &Process, runner: &mut impl apply::Runner, now: u64) -> Result {
        if let Some(saved) = &state.journal.file && !same_target(&self.resolv, saved)? {
            tracing::warn!("resolver link retargeted externally; releasing ownership; check resolver manager configuration");
            Self::release_file(state)?;
        }
        if state.journal.file.is_none() { state.journal.file = Some(read_original(&self.resolv, process)?); }
        let body = file_body(&dns);
        if let Some(original) = &state.journal.file {
            if managed_target(&original.target) { return Err(ApplyError::new(&["DNS", "file fallback"], "enable systemd-resolved or configure DNS manually")); }
            let actual = read_bytes(&original.target)?;
            if nm_generated(actual.as_deref()) {
                return Err(ApplyError::new(&["DNS", "file fallback"], "NetworkManager-generated resolver file; enable systemd-resolved or configure DNS manually"));
            }
            let unchanged = state.journal.owners.iter().any(|o| o.iface == self.iface && o.dns == dns);
            // Reconcile must not promote every instance on every tick. Enforce
            // the current top owner while preserving the original apply order.
            if unchanged && let Some(top) = state.journal.owners.last() {
                let active = file_body(&top.dns);
                if actual.as_deref() == Some(active.as_slice()) { return Ok(()); }
                if now < original.drift_after_ms {
                    return Err(ApplyError::new(&["DNS", "verify file"], "DNS drift repair is in backoff"));
                }
                if let Some(saved) = state.journal.file.as_mut() {
                    saved.drift_delay = if saved.drift_delay == 0 { 2 } else { saved.drift_delay.saturating_mul(2).min(60) };
                    saved.drift_after_ms = now.saturating_add(saved.drift_delay * 1000);
                    stage_write(saved, &active);
                }
                state.save()?;
                tracing::warn!("DNS drift detected; reapplying active exit DNS with backoff");
                if let Some(saved) = &state.journal.file { replace_file(saved, Some(&active), runner)?; }
                return Ok(());
            }
            if original.last_written.is_some() && actual != original.last_written { tracing::warn!("DNS drift detected; reapplying active exit DNS"); }
        }
        state.journal.owners.retain(|owner| owner.iface != self.iface);
        state.journal.owners.push(Owner { iface: self.iface.clone(), dns, process: process.clone() });
        if let Some(original) = state.journal.file.as_mut() {
            stage_write(original, &body); original.drift_delay = 0; original.drift_after_ms = 0;
        }
        state.save()?;
        if let Some(original) = &state.journal.file { replace_file(original, Some(&body), runner)?; }
        Ok(())
    }
    #[cfg(test)]
    fn set_with(&self, dns: &str, runner: &mut impl apply::Runner) -> Result { self.set_mode_with(dns, true, runner) }

    fn set_mode_with(&self, dns: &str, full_tunnel: bool, runner: &mut impl apply::Runner) -> Result {
        let servers: Vec<String> = dns.split_whitespace().map(String::from).collect();
        if servers.is_empty() || servers.iter().any(|s| s.parse::<std::net::IpAddr>().is_err()) {
            return Err(ApplyError::new(&["DNS", "set"], "DNS servers must be IP addresses"));
        }
        let process = Process::current()?;
        let mut state = Locked::open(&self.root)?;
        self.prune(&mut state, &process, runner)?;
        if !self.prefer_resolved || state.journal.owners.iter().any(|owner| owner.iface == self.iface) {
            return self.set_file(&mut state, servers, &process, runner);
        }
        // Only actual command errors are classified as resolved unavailability.
        // Parse and journal failures always propagate, even when kind=NotFound.
        if !state.journal.resolved.contains_key(&self.iface) {
            let queries = (|| {
                let dns = runner.run(&["resolvectl", "dns", &self.iface], None)?;
                let domains = runner.run(&["resolvectl", "domain", &self.iface], None)?;
                Ok((dns, domains))
            })();
            let (dns, domains) = match queries {
                Err(error) if resolved_unavailable(&error) => return self.set_file(&mut state, servers, &process, runner),
                result => result?,
            };
            let saved = Resolved { dns: resolved_values(&dns)?, domains: resolved_values(&domains)?, process: process.clone() };
            state.journal.resolved.insert(self.iface.clone(), saved);
            state.save()?;
        }
        let domains = if full_tunnel { vec!["~.".into()] } else {
            state.journal.resolved.get(&self.iface).map(|s| s.domains.iter().filter(|d| d.as_str() != "~.").cloned().collect()).unwrap_or_default()
        };
        let result = resolved_set(runner, "dns", &self.iface, &servers).and_then(|()| resolved_set(runner, "domain", &self.iface, &domains));
        match result {
            Err(error) if resolved_unavailable(&error) => {
                tracing::warn!(%error, iface = self.iface, "resolved unavailable; saving resolv.conf fallback ownership");
                self.set_file(&mut state, servers, &process, runner)
            }
            result => result,
        }
    }
    fn verify_file_with(&self, runner: &mut impl apply::Runner, now: u64) -> Result {
        let Some(bytes) = read_bytes(&self.root.join("state.json"))? else { return Ok(()); };
        let journal: Journal = serde_json::from_slice(&bytes).map_err(|e| ApplyError::new(&["parse", "DNS journal"], e.to_string()))?;
        // No resolved commands, mkdir or journal mutation for a non-file backend.
        if !journal.owners.iter().any(|o| o.iface == self.iface) { return Ok(()); }
        let mut state = Locked::open(&self.root)?;
        let current = Process::current()?;
        self.prune(&mut state, &current, runner)?;
        let Some(owner) = state.journal.owners.iter().find(|o| o.iface == self.iface) else { return Ok(()); };
        let dns = owner.dns.clone();
        self.set_file_at(&mut state, dns, &current, runner, now)
    }
    fn clear_with(&self, runner: &mut impl apply::Runner) -> Result {
        // No state means no mkdir/lock creation (including read-only rootfs).
        if read_bytes(&self.root.join("state.json"))?.is_none() { return Ok(()); }
        let mut state = Locked::open(&self.root)?;
        self.prune(&mut state, &Process::current()?, runner)?;
        let resolved = (|| { if let Some(saved) = state.journal.resolved.get(&self.iface) {
            let result = apply::all([resolved_set(runner, "dns", &self.iface, &saved.dns), resolved_set(runner, "domain", &self.iface, &saved.domains)]);
            if result.is_ok() { state.journal.resolved.remove(&self.iface); state.save()?; }
            result
        } else { Ok(()) } })();
        let file = (|| {
            let Some(index) = state.journal.owners.iter().position(|owner| owner.iface == self.iface) else { return Ok(()); };
            let top = index + 1 == state.journal.owners.len();
            let removed = state.journal.owners.remove(index);
            if top && let Err(error) = self.restore_file(&mut state, runner) {
                state.journal.owners.push(removed);
                return Err(error);
            }
            state.save()
        })();
        apply::all([resolved, file])
    }
}
impl Dns for Managed {
    fn name(&self) -> &'static str { if self.prefer_resolved { "resolvectl" } else { "resolv" } }
    fn set(&self, dns: &str) -> Result { self.set_mode_with(dns, true, &mut apply::System) }
    fn set_mode(&self, dns: &str, full_tunnel: bool) -> Result { self.set_mode_with(dns, full_tunnel, &mut apply::System) }
    fn owned(&self) -> Result<bool> { Managed::owned(self) }
    fn verify_file(&self) -> Result { self.verify_file_with(&mut apply::System, now_ms()) }
    fn clear(&self) -> Result { self.clear_with(&mut apply::System) }
}

